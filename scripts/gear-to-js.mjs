// Turns src/assets/gear.glb.gz into src/data/gearMesh.js: plain JS arrays (no binary blobs), so the artifact
// page has nothing in it that can't be reviewed for public sharing. Run after re-exporting gear.glb from Blender:
//   node scripts/gear-to-js.mjs
import fs from 'node:fs';
import zlib from 'node:zlib';

const glb = zlib.gunzipSync(fs.readFileSync(new URL('../src/assets/gear.glb.gz', import.meta.url)));
const jsonLen = glb.readUInt32LE(12);
const j = JSON.parse(glb.subarray(20, 20 + jsonLen).toString('utf8'));
const binStart = 20 + jsonLen + 8;
const bin = glb.subarray(binStart, binStart + glb.readUInt32LE(20 + jsonLen));

const ARR = { 5120: Int8Array, 5121: Uint8Array, 5122: Int16Array, 5123: Uint16Array, 5125: Uint32Array, 5126: Float32Array };
const SIZE = { SCALAR: 1, VEC2: 2, VEC3: 3, VEC4: 4 };
function read(i) {
  const a = j.accessors[i], bv = j.bufferViews[a.bufferView];
  const T = ARR[a.componentType], n = a.count * SIZE[a.type];
  const off = bin.byteOffset + (bv.byteOffset || 0) + (a.byteOffset || 0);
  const k = SIZE[a.type], el = T.BYTES_PER_ELEMENT, stride = bv.byteStride || el * k;
  const dv = new DataView(bin.buffer), get = { 1: (o) => (T === Int8Array ? dv.getInt8(o) : dv.getUint8(o)), 2: (o) => (T === Int16Array ? dv.getInt16(o, true) : dv.getUint16(o, true)), 4: (o) => (T === Float32Array ? dv.getFloat32(o, true) : dv.getUint32(o, true)) }[el];
  const data = new Array(n);
  for (let c = 0; c < a.count; c++) for (let q = 0; q < k; q++) data[c * k + q] = get(off + c * stride + q * el);
  return { type: T.name, norm: !!a.normalized, data };
}
const r6 = (v) => +v.toFixed(6);

const mats = j.materials.map((m) => {
  const p = m.pbrMetallicRoughness || {};
  return {
    name: m.name,
    color: (p.baseColorFactor || [1, 1, 1, 1]).slice(0, 3).map(r6),
    metal: r6(p.metallicFactor ?? 1),
    emissive: (m.emissiveFactor || [0, 0, 0]).map(r6),
    strength: r6(m.extensions?.KHR_materials_emissive_strength?.emissiveStrength ?? 1),
  };
});
const nodes = j.scenes[j.scene || 0].nodes.map((ni) => {
  const n = j.nodes[ni];
  if (n.children?.length) throw new Error('nested nodes not supported: ' + n.name);
  return {
    name: n.name,
    t: (n.translation || [0, 0, 0]).map(r6), r: (n.rotation || [0, 0, 0, 1]).map(r6), s: (n.scale || [1, 1, 1]).map(r6),
    prims: j.meshes[n.mesh].primitives.map((p) => ({
      m: p.material, pos: read(p.attributes.POSITION), nrm: read(p.attributes.NORMAL), idx: read(p.indices),
    })),
  };
});
const out = `// Generated by scripts/gear-to-js.mjs from src/assets/gear.glb.gz (art/gear.blend). Do not edit by hand.\n` +
  `export const GEAR_MATS = ${JSON.stringify(mats)};\nexport const GEAR_NODES = ${JSON.stringify(nodes)};\n`;
fs.writeFileSync(new URL('../src/data/gearMesh.js', import.meta.url), out);
console.log(`gearMesh.js: ${nodes.length} models, ${mats.length} materials, ${(out.length / 1024).toFixed(0)} KB`);
