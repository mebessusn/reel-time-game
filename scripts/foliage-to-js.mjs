// Foliage models (v1.13.13): art/src/foliage.py (Blender) builds art/_build/foliage.json; this writes src/data/foliageMesh.js.
//   python3 art/src/foliage.py && node scripts/foliage-to-js.mjs
import fs from 'node:fs';
const data = JSON.parse(fs.readFileSync(process.argv[2] || 'art/_build/foliage.json', 'utf8'));
const out = `// Generated by scripts/foliage-to-js.mjs from art/src/foliage.py (art/foliage.blend). Do not edit by hand.\nexport const FOLIAGE_MESH = ${JSON.stringify(data)};\n`;
fs.writeFileSync('src/data/foliageMesh.js', out);
console.log(`src/data/foliageMesh.js: ${Object.keys(data).length} models, ${(out.length / 1024).toFixed(0)} KB`);
